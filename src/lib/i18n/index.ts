export function messageFor(code: unknown, locale: unknown): string {
	const m = getMessages(locale);
	return typeof code === 'string'
		? m[codes[code] ?? (code in m ? (code as MessageKey) : 'genericError')]
		: m.genericError;
}
export const locationKeys = [
	'school',
	'observatory',
	'workshop',
	'library',
	'garden',
	'tree'
] as const;
export type LocationKey = (typeof locationKeys)[number];
export function locationLabel(location: string, locale: unknown): string {
	return getMessages(locale)[
		locationKeys.includes(location as LocationKey) ? (location as LocationKey) : 'school'
	];
}
export function leagueLabel(band: string, locale: unknown): string {
	const m = getMessages(locale);
	return band === '4-6' ? m.age46 : band === '10-12' ? m.age1012 : m.age79;
}
